import test, { before, after, beforeEach, afterEach } from 'node:test'
import assert from 'node:assert/strict'
import { mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dependency } from './dependencies.mjs'
import { startHarness } from './server.mjs'
const shots = fileURLToPath(new URL('../../docs/ui-review/', import.meta.url))
mkdirSync(shots, { recursive: true })
let browser, page, app, words, errors
const button = key => page.getByRole('button', { name: words[key], exact: true })
const radio = key => page.getByRole('radio', { name: new RegExp('^' + words[key]) })
const field = key => page.getByLabel(words[key], { exact: true })
const count = method => app.calls.filter(call => call.method === method).length
async function open(query = '') {
  await page.goto(app.url + '/' + query)
  words = await page.evaluate(() => plugin._internals[document.documentElement.lang === 'en' ? 'EN' : 'ZH'])
  await page.locator(query.includes('view=settings') ? '.dsha-page .dsha-switch' : '.dsha-entry').waitFor()
}
async function settle(method, before = 0) {
  await page.waitForFunction(({method,before}) => window.__rpcFinished?.[method] > before, {method,before})
}
async function screenshot(name, fullPage = false) {
  await page.evaluate(() => document.fonts.ready)
  await page.screenshot({ path: shots + name + '.png', fullPage })
}
async function noOverflow() {
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
  const panel = page.locator('.dsha-panel')
  if (await panel.count()) { const box = await panel.boundingBox(); assert.ok(box.x >= 0 && box.x + box.width <= page.viewportSize().width + 1) }
}
before(async () => {
  browser = await dependency('playwright').chromium.launch({
    ...(process.env.DSH_UI_CHROMIUM ? {executablePath: process.env.DSH_UI_CHROMIUM} : {}),
    args: ['--no-sandbox', '--disable-dev-shm-usage', '--disable-gpu'],
  })
})
after(async () => browser?.close())
beforeEach(async () => {
  app = await startHarness()
  page = await browser.newPage({ viewport: {width:1280,height:900}, locale: 'zh-CN' })
  page.setDefaultTimeout(7000)
  errors = []
  page.on('pageerror', err => errors.push(err.message))
  page.on('console', msg => { if (msg.type() === 'error') errors.push(msg.text()) })
  await page.addInitScript(() => {
    const original = window.fetch
    window.__rpcFinished = {}
    window.fetch = async (...args) => {
      const result = await original(...args)
      const copy = await result.clone().json().catch(() => null)
      const method = String(args[0]).split('/').pop()
      if(copy) window.__rpcFinished[method] = (window.__rpcFinished[method] || 0) + 1
      return result
    }
  })
})
afterEach(async () => {
  await page.close()
  await app.close()
  assert.deepEqual(errors, [], 'No React errors or browser exceptions')
})

